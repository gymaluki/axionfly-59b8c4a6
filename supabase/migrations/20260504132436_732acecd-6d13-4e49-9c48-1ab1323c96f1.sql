CREATE TABLE public.hyperbuild_licenses (
    id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
    key TEXT NOT NULL UNIQUE,
    lote TEXT,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    expires_at TIMESTAMP WITH TIME ZONE,
    used_by UUID REFERENCES auth.users(id),
    used_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.hyperbuild_licenses ENABLE ROW LEVEL SECURITY;

-- Admin policies
CREATE POLICY "Admin can do everything on licenses"
ON public.hyperbuild_licenses
FOR ALL
USING (EXISTS (
  SELECT 1 FROM public.admin_users
  WHERE email = (SELECT email FROM auth.users WHERE id = auth.uid())
));

-- User policies
CREATE POLICY "Users can view their own licenses"
ON public.hyperbuild_licenses
FOR SELECT
USING (used_by = auth.uid());

-- Function to claim license
CREATE OR REPLACE FUNCTION public.claim_hyperbuild_license()
RETURNS TABLE (license_key TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    target_key TEXT;
BEGIN
    -- Check if user already has a license
    SELECT key INTO target_key
    FROM public.hyperbuild_licenses
    WHERE used_by = auth.uid()
    LIMIT 1;

    IF target_key IS NOT NULL THEN
        RETURN QUERY SELECT target_key;
        RETURN;
    END IF;

    -- Find an available license
    SELECT key INTO target_key
    FROM public.hyperbuild_licenses
    WHERE used_by IS NULL AND status = 'active'
    ORDER BY created_at ASC
    LIMIT 1
    FOR UPDATE SKIP LOCKED;

    IF target_key IS NULL THEN
        RAISE EXCEPTION 'Não há licenças disponíveis no momento.';
    END IF;

    -- Assign the license
    UPDATE public.hyperbuild_licenses
    SET used_by = auth.uid(),
        used_at = now(),
        status = 'used'
    WHERE key = target_key;

    RETURN QUERY SELECT target_key;
END;
$$;

